export function generarPastas({ az, armador, cuantas }) {
  const combos = []
  for (const p of PASTAS) for (const s of SALSAS) if (!p.relleno || s.simple) combos.push([p, s])
  let hechas = 0
  for (const [p, s] of mezclar(az, combos)) {
    if (hechas >= cuantas) break
    const nombre = `${p.n} con ${s.n}`
    const ok = armador.agregar({
      nombre,
      minutos: p.min + s.min,
      comidas: ['almuerzo', 'cena'],
      portable: true,
      kcal: [380, 900],
      prot: 12,
      ingredientes: [[p.s, p.g], ...s.it],
      pasos: [
        p.paso,
        s.paso,
        `Mezclás la pasta con la salsa 1 minuto a fuego bajo, sumando agua de cocción si hace falta. ${elegir(az, ['Servís enseguida.', 'Servís con un poco de queso rallado si querés.', 'Servís bien caliente.', 'Probás y corregís la sal antes de servir.'])}`,
      ],
    })
    if (ok) hechas++
  }
  return hechas
}
