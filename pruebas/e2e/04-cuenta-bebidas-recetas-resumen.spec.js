  await test.step('recetas: favorita, ocultar, mostrar', async () => {
    await pg.goto(APP + '/recetas')
    await pg.waitForSelector('text=para cocinar')
    const total = await pg.locator('a.tarjeta').count()
    await pg.click('button[aria-label="Marcar Fideos con atún como favorita"]')
    await pg.waitForSelector('button[aria-label="Quitar Fideos con atún de favoritas"]')
    await pg.click('button:has-text("Favoritas")')
    await pg.waitForTimeout(200)
    expect(await pg.locator('a.tarjeta').count()).toBe(1)
    expect(await pg.locator('button:has-text("Ocultas")').count()).toBe(0)
    const planeadas = (await rest(pg, 'plan')).filter((r) => r.date >= hoy && r.recipe_id)
    const recetas = new Map((await rest(pg, 'recipes')).map((r) => [r.id, r]))
    const ultima = planeadas[planeadas.length - 1].recipe_id
    const nombre = recetas.get(ultima).name
    await pg.click('button:has-text("Todas")')
    await pg.fill('input[placeholder^="Buscar receta"]', nombre)
    await pg.locator('a.tarjeta').first().click()
    await pg.waitForSelector('text=Ingredientes')
    await pg.click('button:has-text("No me gusta")')
    await pg.waitForSelector('text=Receta oculta')
    await aviso(pg)
    await pg.waitForSelector('text=para cocinar')
    expect(await pg.locator('a.tarjeta').count()).toBe(total - 1)
    const vacias = (await rest(pg, 'plan')).filter((r) => r.date >= hoy && r.recipe_id === ultima)
    expect(vacias).toEqual([])
    await pg.click('button:has-text("Ocultas")')
    await pg.waitForSelector('button:has-text("Mostrar")')
    await captura(pg, 'w13_ocultas', false)
    // el plan no la vuelve a elegir
    await pg.goto(APP + '/plan')
    await pg.waitForSelector('text=Esta semana')
    for (let i = 0; i < 2; i++) {
      if (await pg.locator('button:has-text("Armar con lo que tengo")').isEnabled()) {
        await pg.click('button:has-text("Armar con lo que tengo")')
        await pg.waitForSelector('text=Semana completa')
      }
      await pg.click('button[aria-label="Semana siguiente"]')
      await pg.waitForTimeout(300)
    }
    const otra = (await rest(pg, 'plan')).filter((r) => r.date >= hoy && r.recipe_id === ultima)
    expect(otra, 'el plan volvió a elegir una receta oculta').toEqual([])
    await pg.goto(APP + '/recetas')
    await pg.click('button:has-text("Ocultas")')
    await pg.click('button:has-text("Mostrar")')
    await pg.waitForSelector('text=No tenés recetas ocultas')
    await pg.click('button:has-text("Todas")')
    await pg.waitForTimeout(200)
    expect(await pg.locator('a.tarjeta').count()).toBe(total)
  })

