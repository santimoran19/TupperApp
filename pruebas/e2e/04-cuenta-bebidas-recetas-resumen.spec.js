    // borrar la cuenta de Ana
    await pg.click('button:has-text("Salir")')
    await pg.waitForSelector('text=Iniciar sesión')
    await pg.fill('#email', 'ana@codigo.test')
    await pg.fill('#clave', 'NuevaClave8k')
