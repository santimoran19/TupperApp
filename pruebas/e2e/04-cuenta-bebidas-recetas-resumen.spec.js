    expect(datos.email).toBe('ana@codigo.test')
    expect(datos.perfil.name).toBe('Ana')
    expect(datos.medidas.length).toBe(1)
    await pg.click('button:has-text("Borrar mi cuenta")')
    await pg.waitForSelector('text=No se puede deshacer')
    await captura(pg, 'w06_borrar', false)
    expect(await pg.locator('button:has-text("Borrar todo para siempre")').isDisabled()).toBe(true)
    await pg.fill('#bc-confirmar', 'borrar')
    await pg.click('button:has-text("Borrar todo para siempre")')
