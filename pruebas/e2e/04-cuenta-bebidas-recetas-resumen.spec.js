  await test.step('usuario principal: el diario', async () => {
    ctx = await contexto(browser, { sesion: true })
    pg = await ctx.newPage()
    escuchar(pg, errores, { dialogos: true })
    await pg.goto(APP + '/')
    await pg.waitForSelector('text=¡Hola, Santi!')
    hoy = await hoyEnLaPagina(pg)
    expect(await pg.locator('text=g carbohidratos').count()).toBe(1)
    expect(await pg.locator('text=g grasas').count()).toBe(1)
    // líquido antes
    await pg.locator('span:has(> b)').filter({ hasText: ' L / ' }).innerText()
  })

  await test.step('mate: medidas, termo y azúcar', async () => {
    await pg.locator('section:has-text("BEBIDAS Y ENTRE COMIDAS") button:has-text("Bebida")').click()
    await pg.fill('input[placeholder="Buscar bebida..."]', 'mate')
    await pg.locator('div.divide-y > button').filter({ hasText: 'Mate' }).first().click()
    await pg.waitForSelector('text=Tu plato')
    await pg.inputValue('input[aria-label="Cantidad"]')
    await pg.selectOption('select[aria-label="Tamaño del termo"]', '1200')
    await pg.waitForSelector('button:has-text("Medio termo · 600 ml")')
    await pg.click('button:has-text("Medio termo · 600 ml")')
    expect(await pg.inputValue('input[aria-label="Cantidad"]')).toBe('600')
    await pg.click('button:has-text("Azúcar")')
    await pg.waitForSelector('text=cucharadita en total · 20 kcal')
    await pg.click('button[aria-label="Más azúcar"]')
    await pg.click('button[aria-label="Más azúcar"]')
    await pg.waitForSelector('text=cucharaditas en total · 40 kcal')
    await pg.waitForSelector('text=40 kcal')
    await captura(pg, 'w10_mate')
    await pg.click('button:has-text("Agregar entre comidas")')
    await pg.waitForSelector('text=¡Hola, Santi!')
    await pg.waitForSelector('text=Mate · 600 ml')
    await pg.waitForSelector('text=Azúcar')
    // líquido después del mate
    await pg.locator('span:has(> b)').filter({ hasText: ' L / ' }).innerText()
    const az = (await rest(pg, 'log_entries', `&date=eq.${hoy}&meal=eq.extra`)).filter((r) => r.name === 'Azúcar')
    expect(az.length).toBeGreaterThan(0)
    expect(az[0].qty).toBe(10)
    expect(az[0].kcal).toBe(40)
    const perfil = (await rest(pg, 'profiles'))[0]
    expect(perfil.thermos_ml).toBe(1200)
    // recientes: el mate vuelve con su cantidad y su azúcar
    await pg.goto(APP + '/registrar?comida=extra')
    await pg.waitForSelector('text=Lo que más registrás')
    await pg.locator('p:has-text("Lo que más registrás") + div button').filter({ hasText: 'Mate' }).click()
    expect(await pg.inputValue('input[aria-label="Cantidad"]')).toBe('600')
    await pg.waitForSelector('text=cucharaditas en total · 40 kcal')
    await pg.click('button[aria-label="Quitar"]')
    // café: pocillo, taza, jarro + edulcorante
    await pg.click('button:has-text("Bebida")')
    await pg.fill('input[placeholder="Buscar bebida..."]', 'café negro')
    await pg.locator('div.divide-y > button').first().click()
    await pg.inputValue('input[aria-label="Cantidad"]')
    await pg.click('button:has-text("Edulcorante")')
    await pg.waitForSelector('text=El edulcorante no suma calorías')
    await pg.click('button[aria-label="Quitar"]')
    // cerveza y vino
    for (const bebida of ['Cerveza', 'Vino']) {
      await pg.click('button:has-text("Bebida")')
      await pg.fill('input[placeholder="Buscar bebida..."]', bebida)
      await pg.locator('div.divide-y > button').first().click()
      expect(await pg.locator('text=Endulzado con').count()).toBe(0)
      await pg.click('button[aria-label="Quitar"]')
    }
    // repetir lo de ayer
    const ayer = new Date(Date.parse(hoy + 'T00:00:00Z') - 24 * 60 * 60 * 1000).toISOString().slice(0, 10)
    await pg.evaluate(async ([api, ayer]) => {
      const k = Object.keys(localStorage).find((x) => x.includes('auth-token'))
      const ses = JSON.parse(localStorage.getItem(k))
      const h = { Authorization: 'Bearer ' + ses.access_token, apikey: 'test', 'Content-Type': 'application/json' }
      const foods = await (await fetch(api + '/rest/v1/foods?select=*', { headers: h })).json()
      const f = (s) => foods.find((x) => x.slug === s)
      const filas = [['cena', 'arroz', 70, 252, 4.9], ['cena', 'huevo', 2, 150, 12.5], ['almuerzo', 'fideos', 100, 355, 12]].map(([meal, s, qty, kcal, protein]) => ({ user_id: ses.user.id, date: ayer, meal, name: f(s).name, food_id: f(s).id, qty, kcal, protein, carbs: 0, fat: 0 }))
      await fetch(api + '/rest/v1/log_entries', { method: 'POST', headers: h, body: JSON.stringify(filas) })
    }, [API, ayer])
    await pg.goto(APP + '/registrar?comida=cena')
    await pg.waitForSelector('text=Repetir lo de ayer')
    await pg.click('button:has-text("Repetir lo de ayer")')
    await pg.waitForSelector('text=2 cosas')
    await captura(pg, 'w11_repetir')
  })

